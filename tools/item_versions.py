"""Generates core's ItemVersionsData.java: which Minecraft versions have which items.

Reads each version's own registry report, made by the official server jar's data generator:

    java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports --output <dir>/<version>
    (1.16.5, which has no bundler: java -cp server.jar net.minecraft.data.Main --reports ...)

then:

    python tools/item_versions.py <dir>

where <dir>/<version>/reports/registries.json exists for every version in VERSIONS.

Adding a Minecraft version: add it to VERSIONS (oldest first), make its report, run this. If it
stops on an item that vanished, look the item up: a rename goes in RENAMED, and anything else is
a real removal, which needs a decision before the version can share a market.
"""
import json, os, sys

VERSIONS = ['1.16.5', '1.20.1', '1.21.1', '1.21.11', '26.3']

# Items Mojang renamed. Each keeps its FIRST name in a market forever, because a log must never
# change meaning; versions from `since` on call it `new`. (first name, since, new name)
RENAMED = [
    ('grass_path', '1.20.1', 'dirt_path'),       # renamed in 1.17
    ('grass', '1.21.1', 'short_grass'),          # renamed in 1.20.3
    ('scute', '1.21.1', 'turtle_scute'),         # renamed in 1.20.5
    ('chain', '1.21.11', 'iron_chain'),          # renamed in 1.21.9
]

# In every version's item registry but not something anyone can hold, so never tradable.
NOT_ITEMS = {'air'}

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'core', 'src', 'main', 'java',
                   'io', 'github', 'badbull643', 'economiesmod', 'core', 'ItemVersionsData.java')


def items_of(base, version):
    path = os.path.join(base, version, 'reports', 'registries.json')
    if not os.path.exists(path):
        path = os.path.join(base, version, 'gen', 'reports', 'registries.json')
    reg = json.load(open(path, encoding='utf-8'))
    out = set()
    for key in reg['minecraft:item']['entries']:
        if not key.startswith('minecraft:'):
            sys.exit('%s: unexpected namespace in %s' % (version, key))
        out.add(key[len('minecraft:'):])
    return out - NOT_ITEMS


def main():
    base = sys.argv[1]
    real = {v: items_of(base, v) for v in VERSIONS}
    first_name = {new: old for old, _, new in RENAMED}
    renamed_since = {old: since for old, since, _ in RENAMED}

    # Each version's items, spelled by first names.
    canon = {v: set(first_name.get(i, i) for i in real[v]) for v in VERSIONS}

    for old, since, new in RENAMED:
        si = VERSIONS.index(since)
        for i, v in enumerate(VERSIONS):
            if i < si and new in real[v]:
                sys.exit('%s already exists in %s, before its rename in %s' % (new, v, since))
            if i >= si and old in real[v]:
                sys.exit('%s still exists in %s after being renamed to %s' % (old, v, new))
            if i >= si and new not in real[v]:
                sys.exit('%s missing from %s' % (new, v))

    added = []
    seen = set()
    for i, v in enumerate(VERSIONS):
        if i > 0:
            gone = canon[VERSIONS[i - 1]] - canon[v]
            if gone:
                sys.exit('items vanished in %s and are not renames: %s' % (v, ', '.join(sorted(gone))))
        new = sorted(canon[v] - seen)
        added.append(new)
        seen |= canon[v]

    lines = []
    lines.append('package io.github.badbull643.economiesmod.core;')
    lines.append('')
    lines.append('/**')
    lines.append(' * Generated by tools/item_versions.py from each version\'s own registry report. Do not edit;')
    lines.append(' * rerun the script. Read through {@link ItemVersions}.')
    lines.append(' */')
    lines.append('final class ItemVersionsData {')
    lines.append('    private ItemVersionsData() {}')
    lines.append('')
    lines.append('    /** Oldest first. */')
    lines.append('    static final String[] VERSIONS = {%s};' % ', '.join('"%s"' % v for v in VERSIONS))
    lines.append('')
    lines.append('    /** The items each version added, by first name and without "minecraft:", one string')
    lines.append('     *  per version in VERSIONS order. */')
    lines.append('    static final String[] ADDED = {')
    for v, names in zip(VERSIONS, added):
        lines.append('        // %s: %d' % (v, len(names)))
        chunk = []
        width = 0
        parts = []
        for n in names:
            if width + len(n) + 1 > 88 and chunk:
                parts.append(' '.join(chunk))
                chunk, width = [], 0
            chunk.append(n)
            width += len(n) + 1
        if chunk:
            parts.append(' '.join(chunk))
        if not parts:
            lines.append('        "",')
        else:
            for j, p in enumerate(parts):
                sep = ' +' if j < len(parts) - 1 else ','
                lines.append('        "%s%s"%s' % (p, ' ' if j < len(parts) - 1 else '', sep))
    lines.append('    };')
    lines.append('')
    lines.append('    /** Renamed items: first name, the version the new name starts in, the new name. */')
    lines.append('    static final String[][] RENAMED = {')
    for old, since, new in RENAMED:
        lines.append('        {"%s", "%s", "%s"},' % (old, since, new))
    lines.append('    };')
    lines.append('}')
    lines.append('')

    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    for v, names in zip(VERSIONS, added):
        print('%-8s %4d items, %4d new' % (v, len(canon[v]), len(names)))
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
